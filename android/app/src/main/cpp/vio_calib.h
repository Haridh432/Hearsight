#ifndef HSV2_VIO_CALIB_H
#define HSV2_VIO_CALIB_H

#include <cstdio>
#include <string>

#include "vo.h"

/*
 * OpenVINS camera calibration (Kalibr camchain YAML) for HearSight's grey stream:
 * the colour image at [grayW] x [grayH] (half resolution), no distortion (the D455
 * colour stream is close to distortion-free; refine later if needed).
 * Camera -> IMU: the IMU is taken at the depth origin with the depth axes (IMU -> depth
 * rotation measured as identity on the phone), so from p_color = R p_depth + t:
 *   p_I = R^T (p_C - t)  =>  R_CtoI = R^T, p_CinI = -R^T t.
 * Shared by the app (vio_thread.cpp) and the PC replay tool (tools/vio/replay_vio.cpp).
 */
inline bool writeVioCamchain(const std::string& path, const VoCamera& cam, int grayW, int grayH,
                             const DepthToColor& reg) {
    const double sx = static_cast<double>(grayW) / cam.width;
    const double sy = static_cast<double>(grayH) / cam.height;
    const float* R = reg.rot;   // column-major
    double Rt[3][3], p[3];
    for (int i = 0; i < 3; ++i)
        for (int j = 0; j < 3; ++j) Rt[i][j] = R[i * 3 + j];   // (R^T)[i][j] = R[j][i] = rot[i*3+j]
    for (int i = 0; i < 3; ++i) p[i] = -(Rt[i][0] * reg.trans[0] + Rt[i][1] * reg.trans[1] + Rt[i][2] * reg.trans[2]);
    std::FILE* f = std::fopen(path.c_str(), "w");
    if (!f) return false;
    std::fprintf(f, "%%YAML:1.0\n\n# Generated by HearSight (vio_calib.h).\ncam0:\n  T_imu_cam:\n");
    for (int i = 0; i < 3; ++i) std::fprintf(f, "    - [%.9f, %.9f, %.9f, %.9f]\n", Rt[i][0], Rt[i][1], Rt[i][2], p[i]);
    std::fprintf(f, "    - [0.0, 0.0, 0.0, 1.0]\n");
    std::fprintf(f, "  cam_overlaps: []\n  camera_model: pinhole\n");
    std::fprintf(f, "  distortion_coeffs: [0.0, 0.0, 0.0, 0.0]\n  distortion_model: radtan\n");
    std::fprintf(f, "  intrinsics: [%.4f, %.4f, %.4f, %.4f]\n", cam.fx * sx, cam.fy * sy, cam.cx * sx, cam.cy * sy);
    std::fprintf(f, "  resolution: [%d, %d]\n  rostopic: /cam0/image_raw\n", grayW, grayH);
    std::fclose(f);
    return true;
}

#endif  // HSV2_VIO_CALIB_H
